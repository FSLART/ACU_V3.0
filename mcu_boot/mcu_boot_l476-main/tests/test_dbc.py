"""Keep generated C and Python codecs aligned with the saved DBC."""
from pathlib import Path
import re
import sys
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tools"))
from generate_can import generate, ROOT
from can_upload import DATABASE


class DbcTests(unittest.TestCase):
    def test_generated_files_match_database(self):
        for path, expected in zip((ROOT / "Core/Inc/bootloader.h", ROOT / "Core/Src/bootloader.c"), generate()):
            actual = re.sub(r"(\* @brief This (?:header|source) file was generated by cantools version [^\s]+) .*",
                            r"\1.", path.read_text(encoding="utf-8"))
            self.assertEqual(actual, expected, f"Regenerate {path.name}: python tools/generate_can.py")

    def test_all_messages_and_request_multiplexers_round_trip(self):
        for message in DATABASE.messages:
            for command in range(5) if message.is_multiplexed() else (None,):
                with self.subTest(message=message.name, command=command):
                    values = {signal.name: int(signal.maximum or 0) for signal in message.signals}
                    if command is not None:
                        values["Command"] = command
                    values = message.gather_signals(values)
                    payload = message.encode(values)
                    self.assertEqual(len(payload), 8)
                    self.assertEqual(message.decode(payload, decode_choices=False), values)

    def test_diagnostic_payloads_match_mcu_fixtures(self):
        # Same on-wire fixtures checked by tests/test_heartbeat.c on the Arm CPU.
        fixtures = {
            "BCI_BOOT_HEARTBEAT": "55 78 56 34 12 01 00 00",
            "BCI_BOOT_INFO": "01 01 03 03 00 f8 06 00",
            "BCI_BOOT_FIRMWARE_VERSION": "01 02 56 34 de bc 9a 78",
            "BCI_BOOT_DECISION": "02 09 01 03 78 56 34 12",
            "BCI_BOOT_UPLOAD_STATUS": "01 03 45 23 01 00 f8 06",
            "BCI_BOOT_ERROR": "0b 01 02 03 40 23 01 00",
            "BCI_BOOT_ROLLBACK": "01 02 03 01 44 33 22 11",
            "BCI_BOOT_FLASH_ERROR": "40 23 01 00 04 03 02 01",
            "BCI_BOOT_REJECTED_VERSION": "02 03 67 45 ef cd ab 89",
        }
        for name, hex_bytes in fixtures.items():
            message = DATABASE.get_message_by_name(name)
            payload = bytes.fromhex(hex_bytes)
            self.assertEqual(message.encode(message.decode(payload, decode_choices=False)), payload)
        heartbeat = DATABASE.decode_message(0x581, bytes.fromhex(fixtures["BCI_BOOT_HEARTBEAT"]), decode_choices=False)
        self.assertEqual(heartbeat["Timestamp"], 0x12345678)
        self.assertEqual(heartbeat["BootVersionMajor"], 1)
